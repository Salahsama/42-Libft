void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*p;

	if (nmemb == 0 || size == 0)
		return (malloc(1));
	p = malloc(nmemb * size);
	if (p != NULL)
		ft_memset(p, 0, nmemb * size);
	return (p);
}
